#!/usr/bin/env bash
# Run on OUTBOUND_PROXY_HOST (= spark-master, the only VM with a public IP) with sudo, before 00_prereqs.sh on the others.
# Installs tinyproxy, an HTTP / HTTPS (CONNECT) forward proxy, listening on OUTBOUND_PROXY_PORT and accepting only NFS_NETWORK.
# The workers have no public IP (and a private subnet has no default outbound access), so apt, the Apache archive download,
# the deadsnakes PPA and pip go through this proxy: lib.sh use_outbound_proxy() points them at it.
# Nothing inbound from the internet is opened: the port is reachable only inside spark-vnet.
# Skipped (exit 0) when OUTBOUND_PROXY_HOST is empty.
set -euo pipefail
# shellcheck source=lib.sh
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"
require_root

if [[ -z "${OUTBOUND_PROXY_HOST}" ]]; then
    log "OUTBOUND_PROXY_HOST is empty: every VM has its own outbound internet, no proxy"
    exit 0
fi
is_proxy_host || die "this VM is $(hostname -s) but OUTBOUND_PROXY_HOST=${OUTBOUND_PROXY_HOST}"

export DEBIAN_FRONTEND=noninteractive
if ! command -v tinyproxy > /dev/null 2>&1; then
    apt-get update -y
    apt-get install -y --no-install-recommends tinyproxy
fi

changed=0
if put_file /etc/tinyproxy/tinyproxy.conf 0644 <<EOF
# Generated by infra/cluster/05_proxy.sh
User tinyproxy
Group tinyproxy
Port ${OUTBOUND_PROXY_PORT}
Timeout 600
DefaultErrorFile "/usr/share/tinyproxy/default.html"
StatFile "/usr/share/tinyproxy/stats.html"
LogFile "/var/log/tinyproxy/tinyproxy.log"
LogLevel Warning
PidFile "/run/tinyproxy/tinyproxy.pid"
MaxClients 100
Allow 127.0.0.1
Allow ${NFS_NETWORK}
ViaProxyName "tinyproxy"
# HTTPS (CONNECT) only to the standard port: apt mirrors, PyPI, download.pytorch.org, archive.apache.org, launchpad
ConnectPort 443
EOF
then
    changed=1
fi
systemctl enable tinyproxy > /dev/null 2>&1
if [[ "${changed}" -eq 1 ]] || ! systemctl is-active --quiet tinyproxy; then
    systemctl restart tinyproxy
fi
wait_port 127.0.0.1 "${OUTBOUND_PROXY_PORT}" 30 || die "tinyproxy is not listening on :${OUTBOUND_PROXY_PORT}"
curl -fsS -o /dev/null --max-time 20 -x "http://127.0.0.1:${OUTBOUND_PROXY_PORT}" https://pypi.org/simple/pip/ \
    || die "tinyproxy runs but cannot reach https://pypi.org (outbound internet of $(hostname -s)?)"
log "outbound proxy http://${OUTBOUND_PROXY_HOST}:${OUTBOUND_PROXY_PORT} for ${NFS_NETWORK}"
