
#!/usr/bin/env bash
# Run on EVERY Spark VM (master + all workers; sudo), after 00_prereqs.sh, the NFS scripts and the
# repo sync (it installs requirements from $REPO_DIR on the share). Installs Spark 3.5.1, a
# local Python 3.11 venv at the SAME path on every node, config files and the systemd unit(s).
# Role is detected from the hostname: SPARK_MASTER_HOST -> master, SPARK_WORKER_HOSTS -> worker.
set -euo pipefail
# shellcheck source=lib.sh
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"
require_root
validate_layout

me="$(hostname -s)"
is_master=0
is_worker=0
my_name=""
if [[ "${SPARK_MASTER_HOST%%.*}" == "${me}" ]]; then
    is_master=1
    my_name="${SPARK_MASTER_HOST}"
fi
for w in "${SPARK_WORKER_HOSTS[@]}"; do
    if [[ "${w%%.*}" == "${me}" ]]; then
        is_worker=1
        my_name="${w}"
    fi
done
[[ $((is_master + is_worker)) -gt 0 ]] || die "${me} is neither SPARK_MASTER_HOST nor in SPARK_WORKER_HOSTS"

mountpoint -q "${SHARED_DIR}" || is_nfs_server || die "${SHARED_DIR} is not mounted; run the NFS scripts first"
[[ -f "${REPO_DIR}/requirements.txt" ]] || die "${REPO_DIR}/requirements.txt missing; run: deploy.sh repo"

export DEBIAN_FRONTEND=noninteractive

# ---- Spark ---------------------------------------------------------------------------------
if [[ ! -d "/opt/${SPARK_DIST}" ]]; then
    tmp="$(mktemp -d)"
    url="${APACHE_ARCHIVE}/spark/spark-${SPARK_VERSION}/${SPARK_DIST}.tgz"
    log "downloading ${url}"
    fetch "${url}" "${tmp}/${SPARK_DIST}.tgz"
    verify_sha512 "${tmp}/${SPARK_DIST}.tgz" "${url}.sha512"
    tar -xzf "${tmp}/${SPARK_DIST}.tgz" -C /opt
    rm -rf "${tmp}"
fi
ln -sfn "/opt/${SPARK_DIST}" "${SPARK_HOME}"
install -d -o spark -g spark -m 0755 /var/lib/spark/local /var/lib/spark/work /var/log/spark

# ---- Python 3.11 venv (local disk; identical path on all nodes) -----------------------------
if ! command -v "${PYTHON_BIN}" > /dev/null 2>&1; then
    log "installing ${PYTHON_BIN} from the deadsnakes PPA"
    apt-get install -y --no-install-recommends software-properties-common
    add-apt-repository -y ppa:deadsnakes/ppa
    apt-get update -y
    apt-get install -y --no-install-recommends "${PYTHON_BIN}" "${PYTHON_BIN}-venv"
fi
if [[ ! -x "${VENV_DIR}/bin/python" ]]; then
    "${PYTHON_BIN}" -m venv "${VENV_DIR}"
    "${VENV_DIR}/bin/pip" install --quiet --upgrade pip
fi
"${VENV_DIR}/bin/python" -c 'import sys; sys.exit(0 if sys.version_info[:2] == (3, 11) else 1)' \
    || die "${VENV_DIR} is not Python 3.11 (contract). Delete it and set PYTHON_BIN=python3.11"

log "installing requirements into ${VENV_DIR} (first run takes a few minutes)"
"${VENV_DIR}/bin/pip" install --quiet -r "${REPO_DIR}/requirements.txt"
if [[ "${INSTALL_ML}" == "yes" ]]; then
    "${VENV_DIR}/bin/pip" install --quiet -r "${REPO_DIR}/requirements-ml.txt" \
        --extra-index-url https://download.pytorch.org/whl/cpu
fi
py_spark="$("${VENV_DIR}/bin/python" -c 'import pyspark; print(pyspark.__version__)')"
[[ "${py_spark}" == "${SPARK_VERSION}" ]] || die "pip pyspark is ${py_spark}, cluster Spark is ${SPARK_VERSION}"

# ---- config --------------------------------------------------------------------------------
java_home="$(dirname "$(dirname "$(readlink -f "$(command -v java)")")")"

env_changed=0
if put_file "${SPARK_HOME}/conf/spark-env.sh" 0644 <<EOF
# Generated by infra/cluster/30_spark_node.sh
export JAVA_HOME=${java_home}
export SPARK_LOG_DIR=/var/log/spark
# Without this Spark registers workers/executors by IP address; the health checks and the UI use names.
export SPARK_LOCAL_HOSTNAME=${my_name}
export SPARK_LOCAL_DIRS=/var/lib/spark/local
export SPARK_WORKER_DIR=/var/lib/spark/work
export SPARK_WORKER_CORES=${SPARK_WORKER_CORES}
export SPARK_WORKER_MEMORY=${SPARK_WORKER_MEMORY}
export SPARK_WORKER_OPTS="-Dspark.worker.cleanup.enabled=true -Dspark.worker.cleanup.interval=1800 -Dspark.worker.cleanup.appDataTtl=86400"
export SPARK_DAEMON_MEMORY=${SPARK_DAEMON_MEMORY}
export PYSPARK_PYTHON=${VENV_DIR}/bin/python
# One BLAS/OpenMP thread per Python process. Every executor core already runs one Python worker (pandas,
# numpy, torch in mapInPandas), so extra threads would oversubscribe the cores of a worker VM.
# spark-class sources this file, so it applies to the daemons, the executors they launch and local drivers.
export OMP_NUM_THREADS=1
export MKL_NUM_THREADS=1
export OPENBLAS_NUM_THREADS=1
export NUMEXPR_NUM_THREADS=1
EOF
then
    env_changed=1
fi

# Defaults for any driver started on this node (spark-submit, pyspark, check_spark_cluster.py).
# Executors = workers x (SPARK_WORKER_CORES / SPARK_EXECUTOR_CORES); spark.cores.max = all worker cores
# (trial cluster: 2 workers x 2 cores = 1 executor per worker, 4 cores; full layout: 4 workers x 4 cores = 16).
# Memory per worker VM: executors x (executor.memory + memoryOverhead) + daemon + OS, see the profile / lib.sh.
# The driver runs on the master next to the Kafka container(s), hence the small spark.driver.memory.
# spark.executorEnv.PYTHONPATH makes 'import src...' / 'import contracts...' work on executors
# (the repo is on the share at the same path everywhere).
# spark.jars.packages is NOT set here: each job sets its own Kafka connector (needs Maven access).
# spark.driver.host is pinned only on the master VM (where drivers are meant to run, see README).
driver_host_line="# spark.driver.host not pinned on workers; run drivers on ${SPARK_MASTER_HOST}"
if [[ "${is_master}" -eq 1 ]]; then
    driver_host_line="spark.driver.host                         ${SPARK_MASTER_HOST}"
fi
if put_file "${SPARK_HOME}/conf/spark-defaults.conf" 0644 <<EOF
# Generated by infra/cluster/30_spark_node.sh
spark.master                              ${SPARK_MASTER_URL}
${driver_host_line}
spark.driver.bindAddress                  0.0.0.0
spark.executor.cores                      ${SPARK_EXECUTOR_CORES}
spark.executor.memory                     ${SPARK_EXECUTOR_MEMORY}
spark.executor.memoryOverhead             ${SPARK_EXECUTOR_MEMORY_OVERHEAD}
spark.driver.memory                       ${SPARK_DRIVER_MEMORY}
spark.cores.max                           ${SPARK_CORES_MAX}
spark.executorEnv.PYTHONPATH              ${REPO_DIR}
spark.executorEnv.OMP_NUM_THREADS         1
spark.executorEnv.MKL_NUM_THREADS         1
spark.executorEnv.OPENBLAS_NUM_THREADS    1
spark.executorEnv.NUMEXPR_NUM_THREADS     1
spark.sql.shuffle.partitions              16
spark.pyspark.python                      ${VENV_DIR}/bin/python
spark.pyspark.driver.python               ${VENV_DIR}/bin/python
spark.sql.session.timeZone                UTC
spark.sql.parquet.outputTimestampType     TIMESTAMP_MICROS
EOF
then
    env_changed=1
fi

# ---- systemd -------------------------------------------------------------------------------
unit_changed=0
if [[ "${is_master}" -eq 1 ]]; then
    if put_file /etc/systemd/system/spark-master.service 0644 <<EOF
[Unit]
Description=Spark ${SPARK_VERSION} standalone master
After=network-online.target remote-fs.target
Wants=network-online.target
RequiresMountsFor=${SHARED_DIR}

[Service]
User=spark
Group=spark
ExecStart=${SPARK_HOME}/bin/spark-class org.apache.spark.deploy.master.Master --host ${SPARK_MASTER_HOST} --port 7077 --webui-port 8080
Restart=on-failure
RestartSec=5
LimitNOFILE=65536

[Install]
WantedBy=multi-user.target
EOF
    then
        unit_changed=1
    fi
fi
if [[ "${is_worker}" -eq 1 ]]; then
    if put_file /etc/systemd/system/spark-worker.service 0644 <<EOF
[Unit]
Description=Spark ${SPARK_VERSION} standalone worker
After=network-online.target remote-fs.target
Wants=network-online.target
RequiresMountsFor=${SHARED_DIR}

[Service]
User=spark
Group=spark
ExecStart=${SPARK_HOME}/bin/spark-class org.apache.spark.deploy.worker.Worker --webui-port 8081 --cores ${SPARK_WORKER_CORES} --memory ${SPARK_WORKER_MEMORY} ${SPARK_MASTER_URL}
Restart=always
RestartSec=5
LimitNOFILE=65536

[Install]
WantedBy=multi-user.target
EOF
    then
        unit_changed=1
    fi
fi
[[ "${unit_changed}" -eq 0 ]] || systemctl daemon-reload

restart_if_needed() { # restart_if_needed <unit>
    local unit="$1"
    systemctl enable "${unit}" > /dev/null 2>&1
    if systemctl is-active --quiet "${unit}"; then
        if [[ "${env_changed}" -eq 1 || "${unit_changed}" -eq 1 ]]; then
            systemctl restart "${unit}"
        fi
    else
        systemctl start "${unit}"
    fi
}
[[ "${is_master}" -eq 0 ]] || restart_if_needed spark-master
[[ "${is_worker}" -eq 0 ]] || restart_if_needed spark-worker

log "spark node ready (master=${is_master}, worker=${is_worker}); venv ${VENV_DIR}"
